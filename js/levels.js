const WIDTH = 30;
const HEIGHT = 17;

function paint(drawings) {
  const rows = Array.from({ length: HEIGHT }, () => Array(WIDTH).fill("."));
  for (const [ch, c, r, w = 1, h = 1] of drawings) {
    for (let y = r; y < r + h; y += 1) {
      for (let x = c; x < c + w; x += 1) {
        if (x < 0 || y < 0 || x >= WIDTH || y >= HEIGHT) {
          throw new Error(`Paint ${ch} fell outside the ridge at ${x},${y}`);
        }
        rows[y][x] = ch;
      }
    }
  }
  return rows.map((row) => row.join(""));
}

